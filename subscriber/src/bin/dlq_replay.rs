use serde::Deserialize;

#[derive(Debug, serde::Serialize, Deserialize)]
struct GpsTelemetry {
    event_id: String,
    device_id: String,
    latitude: f64,
    longitude: f64,
    speed_kmh: f64,
}

#[derive(Debug, Deserialize)]
struct DeadLetterRecord {
    dlq_id: String,
    original_stream: String,
    original_subject: String,
    original_sequence: u64,
    consumer: String,
    failure_reason: String,
    delivery_attempts: u64,
    failed_at: String,
    original_event: GpsTelemetry,
}

fn validate_replay(record: &DeadLetterRecord) -> Result<(), Box<dyn std::error::Error>> {
    // Only replay records generated by our GPS processor.
    if record.original_stream != "ORBI_GPS"
        || record.original_subject != "orbi.gps.location"
        || record.consumer != "GPS_PROCESSOR"
    {
        return Err("Unexpected DLQ source or destination".into());
    }

    // This replay tool currently handles max-delivery failures only.
    if record.failure_reason != "MAX_DELIVERIES_EXCEEDED" {
        return Err("Unsupported DLQ failure reason".into());
    }

    // A failed event must have a valid identity.
    if record.original_event.event_id.trim().is_empty()
        || record.original_event.device_id.trim().is_empty()
    {
        return Err("GPS event identity cannot be empty".into());
    }

    // Validate geographic coordinates.
    let gps = &record.original_event;

    if !gps.latitude.is_finite()
        || !gps.longitude.is_finite()
        || !(-90.0..=90.0).contains(&gps.latitude)
        || !(-180.0..=180.0).contains(&gps.longitude)
    {
        return Err("Invalid GPS coordinates".into());
    }

    if !gps.speed_kmh.is_finite() || gps.speed_kmh < 0.0 {
        return Err("Invalid GPS speed".into());
    }

    // Verify that the DLQ identifier corresponds to the source message.
    let expected_id = format!(
        "dlq:{}:{}:{}",
        record.original_stream, record.consumer, record.original_sequence
    );

    if record.dlq_id != expected_id {
        return Err("DLQ identifier does not match the source message".into());
    }

    if record.delivery_attempts == 0 {
        return Err("Invalid delivery attempt count".into());
    }

    println!("Replay eligibility validation passed.");

    Ok(())
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let client = async_nats::connect("127.0.0.1:4222").await?;

    println!("DLQ replay worker connected to NATS");

    let jetstream = async_nats::jetstream::new(client);

    let mut dlq_stream = jetstream.get_stream("ORBI_GPS_DLQ").await?;

    println!("Connected to DLQ stream: ORBI_GPS_DLQ");

    let stream_info = dlq_stream.info().await?;

    println!("Stored DLQ messages: {}", stream_info.state.messages);

    // Retrieve a specific failed message from the DLQ.
    // Sequence 3 contains our first structured dead-letter record.
    let dlq_sequence = 3;

    let message = dlq_stream.get_raw_message(dlq_sequence).await?;

    println!("--- Selected DLQ message ---");
    println!("DLQ sequence: {}", dlq_sequence);
    println!("Subject: {}", message.subject);

    // Deserialize the stored JSON payload.
    let record: DeadLetterRecord = serde_json::from_slice(&message.payload)?;

    println!("--- Dead-letter record ---");

    println!("{record:#?}");

    validate_replay(&record)?;

    println!("Selected event is eligible for manual replay.");
    println!("Event ID: {}", record.original_event.event_id);
    println!("Device ID: {}", record.original_event.device_id);
    println!("Original failure time: {}", record.failed_at);

    // Replay is disabled unless the operator explicitly confirms.
    let confirmed = std::env::args().skip(1).any(|arg| arg == "--confirm");

    if !confirmed {
        println!("Inspection mode: no replay will be performed.");
        println!("To authorize replay, rerun with --confirm.");

        return Ok(());
    }

    println!("Manual replay authorization received.");
    println!("Authorized event: {}", record.original_event.event_id);

    // Use a deterministic identifier for this replay operation.
    // Repeating the same replay produces the same message ID.
    let replay_message_id = format!("replay:{}", record.dlq_id);

    println!("Replay message ID: {}", replay_message_id);

    // Reconstruct the original GPS telemetry payload.
    let replay_payload = serde_json::to_vec(&record.original_event)?;

    println!("Replay payload prepared.");
    println!("Payload size: {} bytes", replay_payload.len());

    // Replay publishing will be implemented in the next lesson.
    // Attach a deterministic message ID for JetStream deduplication.
    let mut headers = async_nats::HeaderMap::new();

    headers.insert("Nats-Msg-Id", replay_message_id.as_str());

    // Publish only the original GPS telemetry, not the DLQ metadata.
    let publish_ack = jetstream
        .publish_with_headers(
            record.original_subject.clone(),
            headers,
            replay_payload.into(),
        )
        .await?
        .await?;

    // JetStream has confirmed acceptance of the publication.
    println!("--- Replay publication confirmed ---");
    println!("Stream: {}", publish_ack.stream);
    println!("Sequence: {}", publish_ack.sequence);
    println!("Duplicate publication: {}", publish_ack.duplicate);
    println!("Replayed event: {}", record.original_event.event_id);

    Ok(())
}
